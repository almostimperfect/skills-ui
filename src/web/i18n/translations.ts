const dictionaries: Record<Locale, Dictionary> = { en, 'zh-CN': zhCN }

export function translate(
  locale: Locale,
  key: TranslationKey,
  params: TranslationParams = {}
): string {
  return dictionaries[locale][key].replace(
    /\{(\w+)\}/g,
    (_, name: string) => String(params[name] ?? `{${name}}`)
  )
}
